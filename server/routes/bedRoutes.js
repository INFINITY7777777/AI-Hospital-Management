// ==========================================================
// EXPRESS
// ==========================================================

const express = require("express");


// ==========================================================
// CREATE ROUTER
// ==========================================================

const router = express.Router();


// ==========================================================
// IMPORT BED CONTROLLERS
// ==========================================================

const {

    addBed,

    getAllBeds,

    getBedById,

    updateBed,

    deleteBed,

    assignBed,

    releaseBed,
    

} = require("../controllers/bedController");


// ==========================================================
// ADD BED
// POST /api/beds
// ==========================================================

router.post(

    "/",

    addBed

);


// ==========================================================
// GET ALL BEDS
// GET /api/beds
// ==========================================================

router.get(

    "/",

    getAllBeds

);


// ==========================================================
// GET BED BY ID
// GET /api/beds/:id
// ==========================================================

router.get(

    "/:id",

    getBedById

);


// ==========================================================
// UPDATE BED
// PUT /api/beds/:id
// ==========================================================

router.put(

    "/:id",

    updateBed

);


// ==========================================================
// DELETE BED
// DELETE /api/beds/:id
// ==========================================================

router.delete(

    "/:id",

    deleteBed

);


// ==========================================================
// ASSIGN BED TO PATIENT
// PUT /api/beds/:id/assign
// ==========================================================

router.put(

    "/:id/assign",

    assignBed

);


// ==========================================================
// RELEASE BED
// PUT /api/beds/:id/release
// ==========================================================

router.put(

    "/:id/release",

    releaseBed

);


// ==========================================================
// EXPORT ROUTER
// ==========================================================

module.exports = router;